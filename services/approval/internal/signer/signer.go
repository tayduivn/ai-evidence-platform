package signer

import (
	"context"
	"errors"
)

var (
	ErrSignerNotFound     = errors.New("signer: requested signer type not registered")
	ErrInvalidSignature   = errors.New("signer: digital signature verification failed")
	ErrCertificateExpired = errors.New("signer: certificate is expired or not yet valid")
	ErrPINRequired        = errors.New("signer: user PIN is required for token operation")
	ErrTokenLocked        = errors.New("signer: token PIN is locked due to too many failed attempts")
	ErrRemoteAuthFailed   = errors.New("signer: remote CA authentication failed")
	ErrRemoteTimeout      = errors.New("signer: remote signing operation timed out")
	ErrInvalidOTP         = errors.New("signer: invalid 2FA/OTP code")
)

// Signer is the core polymorphic interface for all cryptographic signing backends.
type Signer interface {
	// Type returns the unique identifier ("internal", "ca_vn_token", "ca_vn_remote").
	Type() string

	// Sign computes the digital signature over canonical payload bytes.
	// Returns raw signature bytes, PEM-encoded X.509 certificate, and any error.
	Sign(ctx context.Context, payload []byte) (signature []byte, certPEM []byte, err error)

	// Verify validates that the signature was generated by the private key corresponding
	// to certPEM over the given canonical payload bytes.
	Verify(ctx context.Context, payload []byte, signature []byte, certPEM []byte) (bool, error)

	// GetCertificateChain retrieves the complete X.509 certificate hierarchy
	// (leaf certificate, intermediate CAs, and root CA) in PEM format.
	GetCertificateChain(ctx context.Context) ([][]byte, error)
}
